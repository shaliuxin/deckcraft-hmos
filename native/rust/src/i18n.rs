/// 动态串：`format!` 生成的文本没有固定的完整字面量，单独做少量结构化规则。
fn dynamic(text: &str) -> Option<String> {
    // 退出 / 关闭未保存确认："Do you want to save the changes you made to “X”?" / "... to N presentations?"
    if let Some(rest) = text.strip_prefix("Do you want to save the changes you made to ") {
        if let Some(inner) = rest.strip_suffix("?") {
            if let Some(n) = inner.strip_suffix(" presentations") {
                if !n.is_empty() && n.chars().all(|c| c.is_ascii_digit()) {
                    return Some(format!("您要保存对 {n} 个演示文稿所做的更改吗？"));
                }
            }
            return Some(format!("您要保存对 {inner} 所做的更改吗？"));
        }
    }
    // 从其它演示文稿插入幻灯片："Insert slides from “X” after the current slide:"
    if let Some(rest) = text.strip_prefix("Insert slides from ") {
        if let Some(name) = rest.strip_suffix(" after the current slide:") {
            return Some(format!("从 {name} 插入幻灯片到当前幻灯片之后："));
        }
    }
    // 找不到对象："DeckCraft can't find “X”."
    if let Some(rest) = text.strip_prefix("DeckCraft can't find “") {
        if let Some(inner) = rest.strip_suffix("”.") {
            return Some(format!("DeckCraft 找不到“{inner}”。"));
        }
    }
    // 状态栏 "Slide 3 of 12"
    if let Some(rest) = text.strip_prefix("Slide ") {
        let mut parts = rest.splitn(3, " of ");
        let n = parts.next()?;
        let m = parts.next()?;
        if parts.next().is_none() && !n.is_empty() && !m.is_empty()
            && n.chars().all(|c| c.is_ascii_digit())
            && m.chars().all(|c| c.is_ascii_digit())
        {
            return Some(format!("第 {n} 张，共 {m} 张"));
        }
    }
    // 标题栏文档名 "Presentation12 — Edited"（编辑态）
    if let Some(rest) = text.strip_suffix(" — Edited") {
        if let Some(n) = rest.strip_prefix("Presentation") {
            if !n.is_empty() && n.chars().all(|c| c.is_ascii_digit()) {
                return Some(format!("演示文稿{n} — 已编辑"));
            }
        }
    }
    // 文档名 "Presentation12"
    if let Some(n) = text.strip_prefix("Presentation") {
        if !n.is_empty() && n.chars().all(|c| c.is_ascii_digit()) {
            return Some(format!("演示文稿{n}"));
        }
    }
    // backstage 的 "•  文本" 项目符号行
    if let Some(rest) = text.strip_prefix("•  ") {
        if let Some(zh) = exact(rest) {
            return Some(format!("•  {zh}"));
        }
    }
    // 带省略号的命令标签（"Font…" 已在表内，这里兜住其它）
    if let Some(rest) = text.strip_suffix("…") {
        if let Some(zh) = exact(rest) {
            return Some(format!("{zh}…"));
        }
    }
    None
}

/// 词级兜底：整句由 2–5 个已知 UI 单词组成且每个词都命中时才拼译，
/// 避免把用户输入的任意英文句子改得面目全非。
fn words(text: &str) -> Option<String> {
    if !text.chars().next()?.is_ascii_uppercase() {
        return None;
    }
    let parts: Vec<&str> = text.split(' ').collect();
    if !(2..=5).contains(&parts.len()) || parts.iter().any(|p| p.is_empty()) {
        return None;
    }
    let mut out = String::new();
    for part in parts {
        let zh = word(part)?;
        out.push_str(zh);
    }
    Some(out)
}

