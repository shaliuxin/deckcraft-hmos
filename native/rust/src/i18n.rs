//! 中文界面与「跟随系统语言」自适应。
//!
//! 上游 DeckCraft 0.15.0 **没有** i18n catalog、没有语言切换开关、也没有翻译宏
//! （`docs/localization-parity.md` 自述 English-only，约 1,050 条 UI 字面量散落在
//! `crates/ui-egui/src`、`crates/engine/src/cmd` 与 `crates/model/src`）。
//! 逐条改上游会破坏「上游源码零改动」的移植约定，也要碰 117 个文件。
//!
//! 因此采用**宿主注入式翻译**：vendored `storytold/egui` fork 在
//! `RichText::new` 与 `From<…> for WidgetText` 处暴露一个
//! `fn(&str) -> Option<String>` 钩子（见 `scripts/apply_egui_i18n_patch.py`），
//! 所有 label / button / menu / tooltip / 命令标签在构造 WidgetText 时都会过一遍
//! 本文件的 `translate()`。翻译表按**完整字符串精确匹配**，未命中一律原样返回，
//! 因此命令 ID、字体名、路径、用户输入的幻灯片文本都不会被误改。
//!
//! 语言状态是一个 `AtomicBool`：系统语言以 `zh` 开头 → 中文，其它 → 英文原版。
//! `dc_init` 时按 ArkTS 上报的 `language` / `systemLocale` 设定；系统语言在运行中
//! 变化时可再调 `set_locale()`，下一次重绘即生效，无需重建 egui Context。

use std::sync::atomic::{AtomicBool, Ordering};

static ZH_ACTIVE: AtomicBool = AtomicBool::new(false);

/// 在 `dc_init` 里、任何 UI 构造之前调用一次。
pub fn install() {
    egui::i18n::install_translator(translate);
    // 画布上的空占位符提示不走 egui 排版（deckcraft_render 直接把 glyph 画出来），
    // 单独给上游 model 的 PhType::prompt() 装同一个语言开关下的翻译器。
    deckcraft_model::i18n::install_prompt_translator(|s| if active() { exact(s) } else { None });
}

pub fn active() -> bool {
    ZH_ACTIVE.load(Ordering::Relaxed)
}

/// 按系统 locale 决定界面语言，返回是否启用中文。
/// `zh-Hans-CN` / `zh_CN` / `zh` 均识别为中文；`en-US` 等保持英文原版。
pub fn set_locale(locale: &str, language: &str) -> bool {
    let tag = normalized(locale, language);
    let zh = tag.starts_with("zh");
    ZH_ACTIVE.store(zh, Ordering::Relaxed);
    log::info!("i18n: locale={tag} -> {}", if zh { "zh-Hans" } else { "en" });
    zh
}

fn normalized(locale: &str, language: &str) -> String {
    [locale, language]
        .into_iter()
        .map(str::trim)
        .find(|s| !s.is_empty())
        .unwrap_or("en")
        .replace('_', "-")
        .to_ascii_lowercase()
}

/// egui 的翻译钩子。**只做完整字符串精确匹配**，命中才分配字符串。
pub fn translate(text: &str) -> Option<String> {
    if !active() {
        return None;
    }
    if let Some(zh) = exact(text) {
        return Some(zh.to_owned());
    }
    if let Some(zh) = dynamic(text) {
        return Some(zh);
    }
    words(text)
}

